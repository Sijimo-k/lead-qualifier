// `--check` fails when the committed workflow files are out of date (used by the tests).
const check = process.argv.includes("--check");
mkdirSync(new URL("workflows/", root), { recursive: true });
let stale = 0;
for (const [file, wf] of [
  ["workflows/lead-qualifier.json", qualify],
  ["workflows/followup-drafts.json", followup],
]) {
  const json = JSON.stringify(wf, null, 2) + "\n";
  if (check) {
    let current = "";
    try {
      current = read(file);
    } catch {
      current = "";
    }
    if (current.replace(/\r\n/g, "\n") !== json) {
      stale += 1;
      console.error(`${file} is out of date - run npm run build`);
    }
  } else {
    writeFileSync(new URL(file, root), json);
    console.log(`wrote ${file} (${wf.nodes.length} nodes)`);
  }
}
if (stale > 0) process.exit(1);
