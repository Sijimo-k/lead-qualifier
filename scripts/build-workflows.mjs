const hubspotUrl = (path) => `={{ ($env.HUBSPOT_BASE_URL || 'https://api.hubapi.com') + '${path}' }}`;
const SLACK_URL = "={{ $env.SLACK_WEBHOOK_URL }}";

function layout(nodes, positions) {
  return nodes.map((node, i) => ({ id: `${slug(node.name)}-${i}`, position: positions[node.name], ...node }));
}
const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

function connections(edges) {
  const out = {};
  for (const [from, outputIndex, to] of edges) {
    out[from] ??= { main: [] };
    while (out[from].main.length <= outputIndex) out[from].main.push([]);
    out[from].main[outputIndex].push({ node: to, type: "main", index: 0 });
  }
  return out;
}

function workflow(id, name, nodes, positions, edges) {
  return {
    id,
    name,
    nodes: layout(nodes, positions),
    connections: connections(edges),
    settings: { executionOrder: "v1" },
    pinData: {},
  };
}

