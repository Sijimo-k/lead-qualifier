// Builds the n8n workflow JSON files in workflows/.
// The Code nodes get the tested functions from src/ inlined (n8n Code nodes
// cannot import local files), so the logic that runs in n8n is exactly the
// logic covered by `npm test`. Edit src/ or this file, then run `npm run build`.

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";

const root = new URL("../", import.meta.url);
const read = (path) => readFileSync(new URL(path, root), "utf8");
const business = read("config/business.json").trim();
const rubric = read("config/rubric.json").trim();

function inline(...modules) {
  return modules
    .map((m) => `// ---- from ${m} ----\n` + read(m).replace(/^export /gm, ""))
    .join("\n");
}

function code(name, { modules = [], config = [], body, mode = "runOnceForEachItem" }) {
  const consts = [];
  if (config.includes("business")) consts.push(`const BUSINESS = ${business};`);
  if (config.includes("rubric")) consts.push(`const RUBRIC = ${rubric};`);
  const jsCode = [
    "// GENERATED by scripts/build-workflows.mjs from src/ - edit src/ and run `npm run build`.",
    ...consts,
    inline(...modules),
    "// ---- node logic ----",
    body.trim(),
    "",
  ].join("\n");
  return { name, type: "n8n-nodes-base.code", typeVersion: 2, parameters: { mode, jsCode } };
}

function http(name, { method, url, credential, jsonBody, headers = [], onError, retry = true }) {
  const node = {
    name,
    type: "n8n-nodes-base.httpRequest",
    typeVersion: 4.2,
    parameters: {
      method,
      url,
      sendBody: true,
      specifyBody: "json",
      jsonBody,
      options: { timeout: 120000 },
    },
  };
  if (credential) {
    node.parameters.authentication = "genericCredentialType";
    node.parameters.genericAuthType = "httpHeaderAuth";
    node.credentials = { httpHeaderAuth: credential };
  }
  if (headers.length > 0) {
    node.parameters.sendHeaders = true;
    node.parameters.headerParameters = { parameters: headers };
  }
  if (retry) Object.assign(node, { retryOnFail: true, maxTries: 3, waitBetweenTries: 3000 });
  if (onError) node.onError = onError;
  return node;
}

function ifNode(name, leftValue, rightValue) {
  return {
    name,
    type: "n8n-nodes-base.if",
    typeVersion: 2,
    parameters: {
      conditions: {
        options: { caseSensitive: true, leftValue: "", typeValidation: "loose" },
        conditions: [
          {
            id: `${name}-condition`.replace(/\W+/g, "-").toLowerCase(),
            leftValue,
            rightValue,
            operator: { type: "boolean", operation: "equals" },
          },
        ],
        combinator: "and",
      },
      options: {},
    },
  };
}

function respond(name, responseBody, responseCode = 200) {
  return {
    name,
    type: "n8n-nodes-base.respondToWebhook",
    typeVersion: 1.1,
    parameters: { respondWith: "json", responseBody, options: { responseCode } },
  };
}

// Credentials are referenced by name; you create them once in n8n (see README).
